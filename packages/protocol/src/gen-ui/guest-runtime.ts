// 一个文件=一种作用：Gen UI 沙箱内的 guest 运行时脚本——安装 `window.zcode` 风格的应用内桥、
// 处理宿主下发的上下文通知（`zcode/gen-ui/context`），并登记 Tweak 绑定。
//
// 为什么是「脚本字符串」而不是可导入模块：这段代码要跑在**不透明源**的沙箱 iframe 里
// （sandbox 无 allow-same-origin），宿主无法把它当作同源模块 import；上游同样是把
// 运行时产物内联进页面（`__ZCODE_GEN_UI_RUNTIME__` 槽位）。故这里以自包含 IIFE 源码
// 形式导出，宿主用 `buildGenUiGuestRuntimeScript()` 取字符串后内联注入。
//
// b07 差异（相对上游 `renderer/src/plugin-sandbox/genUi.ts` + `genUiTweakRuntime.js`）：
// - 不引入官方 @modelcontextprotocol/ext-apps SDK：握手/上下文改走本包 host-bridge 的
//   轻量 JSON-RPC 通知（`zcode/gen-ui/context`），与 b07 的 MCP 桥共用同一 postMessage 通道；
// - 不移植外链 `openExternal`（上游经 SDK openLink + 手势门）——b07 的外链由工作台统一负责，
//   沙箱内不提供导航能力，故 `window.zcode` 只暴露 widgetState / setWidgetState /
//   sendFollowUpMessage / onContext；
// - Tweak 运行时保留「宿主拥有全部控件 UI」的分工，但去掉了上游的标注遮罩选中/escape
//   手势（b07 无 overlay，控件在工作台侧栏渲染），只保留 register/update/dispose 与预览回填。

/** 宿主替换该标记以注入运行时脚本（对齐上游 `__ZCODE_GEN_UI_RUNTIME__` 槽位）。 */
export const GEN_UI_GUEST_RUNTIME_MARKER = '__ZCODE_GEN_UI_RUNTIME__';
/** 初始 Widget 状态的承载元素 id（宿主把状态快照写进这个 `<script type="application/json">`）。 */
export const GEN_UI_INITIAL_STATE_ELEMENT_ID = 'zcode-gen-ui-initial-state';

/**
 * 自包含 guest 运行时源码。求值后立即执行，向 `window` 安装 `window.zcode`。
 * 刻意不引用任何模块级标识符，保证作为独立脚本在沙箱文档里可运行。
 */
const GUEST_RUNTIME_SOURCE = [
  '(function () {',
  "  'use strict';",
  '  var win = window;',
  '  var doc = document;',
  '  var parent = win.parent;',
  "  var GLOBALS_EVENT = 'zcode:set_globals';",
  "  var CONTEXT_METHOD = 'zcode/gen-ui/context';",
  "  var STATE_METHOD = 'zcode/gen-ui/state';",
  "  var FOLLOW_UP_METHOD = 'zcode/gen-ui/follow-up';",
  "  var TWEAK_METHOD = 'zcode/gen-ui/tweak';",
  '  var pending = Object.create(null);',
  '  var nextId = 1;',
  '  var state = null;',
  '  var saves = Promise.resolve();',
  '  function clone(value) {',
  '    return value === null || value === undefined ? null : JSON.parse(JSON.stringify(value));',
  '  }',
  '  function post(method, params) {',
  '    var id = nextId++;',
  '    return new Promise(function (resolve, reject) {',
  '      pending[id] = { resolve: resolve, reject: reject };',
  "      parent.postMessage({ jsonrpc: '2.0', id: id, method: method, params: params }, '*');",
  '    });',
  '  }',
  '  function readInitial() {',
  "    var node = doc.getElementById('zcode-gen-ui-initial-state');",
  '    if (!node) return;',
  '    try {',
  "      var parsed = JSON.parse(node.textContent || 'null');",
  '      state = parsed === null ? null : parsed;',
  '    } catch (error) {',
  '      state = null;',
  '    }',
  '  }',
  '  function normalizeState(value) {',
  "    if (value === null || typeof value !== 'object') throw new TypeError('Widget state must be an object');",
  "    var keys = Object.keys(value);",
  "    for (var i = 0; i < keys.length; i++) if (keys[i] !== 'modelContent' && keys[i] !== 'privateContent') throw new TypeError('Unknown widget state key');",
  "    return { modelContent: value.modelContent === undefined ? null : value.modelContent, privateContent: value.privateContent === undefined ? null : value.privateContent };",
  '  }',
  '  function normalizeFollowUp(value) {',
  "    if (!value || typeof value !== 'object' || typeof value.prompt !== 'string') throw new TypeError('sendFollowUpMessage requires a prompt');",
  "    var prompt = value.prompt.trim();",
  "    if (!prompt) throw new TypeError('sendFollowUpMessage requires a non-empty prompt');",
  '    return value.title === undefined ? { prompt: prompt } : { prompt: prompt, title: value.title };',
  '  }',
  '  function applyGlobals(globals) {',
  '    if (Object.prototype.hasOwnProperty.call(globals, "widgetState")) {',
  '      state = globals.widgetState === null ? null : globals.widgetState;',
  '    }',
  "    if (globals.theme === 'dark' || globals.theme === 'light') {",
  '      doc.documentElement.dataset.theme = globals.theme;',
  '      doc.documentElement.style.colorScheme = globals.theme;',
  '    }',
  '    win.dispatchEvent(new CustomEvent(GLOBALS_EVENT, { detail: { globals: {',
  '      widgetState: clone(state),',
  '      theme: doc.documentElement.dataset.theme,',
  '      visualizationAnnotation: globals.visualizationAnnotation === undefined ? null : globals.visualizationAnnotation',
  '    } } }));',
  '  }',
  "  win.addEventListener('message', function (event) {",
  '    if (event.source !== parent) return;',
  '    var data = event.data;',
  "    if (!data || typeof data !== 'object' || data.jsonrpc !== '2.0') return;",
  "    if (typeof data.id !== 'undefined' && pending[data.id]) {",
  '      var entry = pending[data.id];',
  '      delete pending[data.id];',
  "      if (data.error) entry.reject(new Error(data.error.message || 'gen-ui-error'));",
  '      else entry.resolve(data.result);',
  '      return;',
  '    }',
  '    if (data.method === CONTEXT_METHOD) applyGlobals(data.params || {});',
  '  });',
  '  var api = {',
  '    get widgetState() { return clone(state); },',
  '    setWidgetState: function (value) {',
  '      var next = normalizeState(value);',
  '      var save = saves.catch(function () {}).then(function () { return post(STATE_METHOD, { state: next }); });',
  '      saves = save;',
  '      return save;',
  '    },',
  '    sendFollowUpMessage: function (value) {',
  '      var params = normalizeFollowUp(value);',
  '      return saves.then(function () { return post(FOLLOW_UP_METHOD, params); });',
  '    },',
  '    onContext: function (listener) {',
  '      var handler = function (event) { listener(event.detail.globals); };',
  '      win.addEventListener(GLOBALS_EVENT, handler);',
  '      return function () { win.removeEventListener(GLOBALS_EVENT, handler); };',
  '    }',
  '  };',
  "  Object.defineProperty(win, 'zcode', { value: Object.freeze(api), writable: false, configurable: false });",
  '  // Tweak 运行时：宿主拥有全部控件 UI，这里只登记绑定并回填预览值。',
  '  var panels = Object.create(null);',
  '  var nextPanelId = 0;',
  '  var command = null;',
  '  function liveTarget(panel) {',
  '    var target = panel.target;',
  "    return target && target.isConnected ? target : null;",
  '  }',
  '  function isValue(control, value) {',
  "    if (control.type === 'range') return typeof value === 'number' && isFinite(value) && value >= control.min && value <= control.max;",
  "    if (control.type === 'color') return typeof value === 'string' && /^#(?:[0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$/i.test(value);",
  "    if (control.type === 'toggle') return typeof value === 'boolean';",
  "    if (control.type === 'select') return typeof value === 'string' && control.options.some(function (option) { return option.value === value; });",
  '    return false;',
  '  }',
  '  function setValue(binding, value) {',
  '    if (!liveTarget(binding.panel)) return;',
  '    if (binding.object[binding.property] === value) return;',
  '    binding.object[binding.property] = value;',
  '    if (typeof binding.panel.onChange === "function") binding.panel.onChange();',
  '  }',
  '  function syncPreviews() {',
  '    var desired = [];',
  '    var changes = (command && command.changes) || [];',
  '    for (var i = 0; i < changes.length; i++) {',
  '      var change = changes[i];',
  '      var panel = panels[change.registrationId];',
  '      if (!panel || panel.targetId !== change.targetId) continue;',
  '      for (var j = 0; j < change.annotationControlChanges.length; j++) {',
  '        var edit = change.annotationControlChanges[j];',
  '        var binding = panel.bindings[edit.callback];',
  '        var control = panel.accepted && panel.accepted.filter(function (item) { return item.callback === edit.callback; })[0];',
  '        if (binding && control && edit.previousValue === control.currentValue && edit.value !== control.currentValue && isValue(control, edit.value)) {',
  '          desired.push([binding, edit.value]);',
  '        }',
  '      }',
  '    }',
  '    var previous = panelPreviews;',
  '    panelPreviews = desired;',
  '    for (var k = 0; k < previous.length; k++) {',
  '      if (panelPreviews !== desired) return;',
  '      var stale = previous[k];',
  '      if (desired.indexOf(stale) === -1) setValue(stale[0], stale[0].control.currentValue);',
  '    }',
  '    for (var m = 0; m < desired.length; m++) {',
  '      if (panelPreviews !== desired) return;',
  '      setValue(desired[m][0], desired[m][1]);',
  '    }',
  '  }',
  '  var panelPreviews = [];',
  '  function targetSnapshot(panel) {',
  '    var target = liveTarget(panel);',
  "    if (!target) throw new TypeError('Tweak container is unavailable');",
  '    var label = target.getAttribute("aria-label") || target.getAttribute("title") || target.id || target.localName;',
  '    var rect = target.getBoundingClientRect();',
  '    return {',
  '      id: panel.targetId,',
  '      label: String(label).replace(/\\s+/g, " ").trim().slice(0, 80),',
  '      selector: target.id ? "#" + target.id : target.localName,',
  '      tagName: target.localName.toLowerCase(),',
  '      rect: { x: rect.x, y: rect.y, width: rect.width, height: rect.height }',
  '    };',
  '  }',
  '  function queue(panel, control, target) {',
  '    panel.pending = panel.pending.then(function () {',
  '      if (panel.disposed) return;',
  '      if (!liveTarget(panel)) { disposePanel(panel); return; }',
  '      var type = panel.accepted === null ? "register" : "update";',
  '      var controls = (panel.accepted || []).concat([control]);',
  '      return post(TWEAK_METHOD, {',
  '        type: type,',
  '        registrationId: panel.id,',
  '        annotationControls: { controlsMode: "replace", controls: controls },',
  '        targets: [target]',
  '      }).then(function (result) {',
  '        if (panel.disposed) return;',
  '        if (result && result.annotationControls && result.annotationControls.controls) {',
  '          panel.accepted = result.annotationControls.controls;',
  '        } else {',
  '          panel.controls = panel.controls.filter(function (item) { return item.callback !== control.callback; });',
  '          delete panel.bindings[control.callback];',
  '          if (type === "register") disposePanel(panel);',
  '        }',
  '        syncPreviews();',
  '      });',
  '    });',
  '  }',
  '  function disposePanel(panel) {',
  '    if (panel.disposed) return;',
  '    panel.disposed = true;',
  '    if (panels[panel.id]) {',
  '      delete panels[panel.id];',
  '      syncPreviews();',
  '      void panel.pending.then(function () { return post(TWEAK_METHOD, { type: "dispose", registrationId: panel.id }); });',
  '    }',
  '    panel.bindings = Object.create(null);',
  '    panel.controls = [];',
  '    panel.accepted = null;',
  '  }',
  '  function bind(object, property, definition) {',
  '    var panel = this.__panel;',
  '    if (this.__disposed || !panel || panel.disposed) throw new Error("Tweak has been disposed");',
  '    if (!isValue(definition, definition.currentValue)) throw new TypeError("Tweak bindings require a valid current value");',
  '    if (panel.controls.length >= 12) throw new RangeError("Too many Tweak controls");',
  '    var callback = panel.id + "-" + (++panel.nextControlId);',
  '    var control = Object.assign({}, definition, { callback: callback });',
  '    panel.controls = panel.controls.concat([control]);',
  '    panel.bindings[callback] = { panel: panel, object: object, property: property, control: control };',
  '    panels[panel.id] = panel;',
  '    queue(panel, control, targetSnapshot(panel));',
  '    return this;',
  '  }',
  '  function Tweak(options) {',
  '    options = options || {};',
  '    var container = options.container;',
  '    if (!container || typeof container.getBoundingClientRect !== "function") throw new TypeError("Tweak needs a container element");',
  '    var targetId = container.id || "target-" + (++nextPanelId);',
  '    this.__panel = {',
  '      id: "tweak-" + (++nextPanelId),',
  '      targetId: targetId,',
  '      target: container,',
  '      onChange: options.onChange,',
  '      bindings: Object.create(null),',
  '      nextControlId: 0,',
  '      controls: [],',
  '      accepted: null,',
  '      pending: Promise.resolve(),',
  '      disposed: false',
  '    };',
  '    this.__disposed = false;',
  '  }',
  '  Tweak.prototype.addSlider = function (object, property, options) {',
  '    options = options || {};',
  '    return bind.call(this, object, property, {',
  '      type: "range",',
  '      label: options.unit ? (options.label || property) + " (" + options.unit + ")" : (options.label || property),',
  '      reference: options.reference,',
  '      currentValue: object[property],',
  '      min: options.min,',
  '      max: options.max,',
  '      step: options.step === undefined ? 1 : options.step',
  '    });',
  '  };',
  '  Tweak.prototype.addColorPicker = function (object, property, options) {',
  '    options = options || {};',
  '    return bind.call(this, object, property, { type: "color", label: options.label || property, reference: options.reference, currentValue: object[property] });',
  '  };',
  '  Tweak.prototype.addToggle = function (object, property, options) {',
  '    options = options || {};',
  '    return bind.call(this, object, property, { type: "toggle", label: options.label || property, reference: options.reference, currentValue: object[property] });',
  '  };',
  '  Tweak.prototype.addSelect = function (object, property, options) {',
  '    options = options || {};',
  '    var mapped = (options.options || []).map(function (option) {',
  '      return typeof option === "string" ? { label: option, value: option } : { label: option.label, value: option.value };',
  '    });',
  '    return bind.call(this, object, property, { type: "select", label: options.label || property, reference: options.reference, currentValue: object[property], options: mapped });',
  '  };',
  '  Tweak.prototype.dispose = function () {',
  '    this.__disposed = true;',
  '    if (this.__panel) disposePanel(this.__panel);',
  '  };',
  "  win.addEventListener('zcode:set_globals', function (event) {",
  '    var globals = event.detail && event.detail.globals;',
  '    if (!globals || !Object.prototype.hasOwnProperty.call(globals, "visualizationAnnotation")) return;',
  '    command = globals.visualizationAnnotation;',
  '    syncPreviews();',
  '  });',
  "  win.addEventListener('pagehide', function () {",
  '    for (var id in panels) if (Object.prototype.hasOwnProperty.call(panels, id)) disposePanel(panels[id]);',
  '  });',
  "  Object.defineProperty(win, 'Tweak', { value: Tweak, writable: false, configurable: false });",
  '  readInitial();',
  '})();',
].join('\n');

/** 返回可内联注入沙箱文档的 guest 运行时脚本（自包含 IIFE）。 */
export function buildGenUiGuestRuntimeScript(): string {
  return GUEST_RUNTIME_SOURCE;
}

/**
 * 把 guest 运行时脚本内联进页面 HTML：替换运行时槽位标记；没有槽位时在 `</head>` 前
 * 或文档最前插入。内联脚本里的 `</script` 已转义，避免提前闭合宿主脚本标签。
 */
export function injectGenUiGuestRuntime(html: string, marker: string = GEN_UI_GUEST_RUNTIME_MARKER): string {
  const tag = `<script>${GUEST_RUNTIME_SOURCE.replaceAll('</script', '<\\/script')}</script>`;
  if (html.includes(marker)) return html.replaceAll(marker, tag);
  const headMatch = /<\/head>/i.exec(html);
  if (headMatch) return `${html.slice(0, headMatch.index)}${tag}${html.slice(headMatch.index)}`;
  return `${tag}${html}`;
}

/**
 * 把初始 Widget 状态快照写进页面（宿主渲染前调用）：`<script type="application/json">`。
 * 状态在宿主侧已按 16KiB 上限校验，这里只做序列化，`<` 转义避免破坏脚本标签。
 */
export function injectGenUiInitialState(html: string, state: unknown): string {
  const json = JSON.stringify(state ?? null).replaceAll('<', '\\u003c');
  const tag = `<script id="${GEN_UI_INITIAL_STATE_ELEMENT_ID}" type="application/json">${json}</script>`;
  const headMatch = /<\/head>/i.exec(html);
  if (headMatch) return `${html.slice(0, headMatch.index)}${tag}${html.slice(headMatch.index)}`;
  return `${tag}${html}`;
}
